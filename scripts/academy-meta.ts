// TEKA NEXUS — regenerate src/lib/academy/meta.ts from the real course content.
//
// WHY THIS EXISTS: the client components (landing, about, portal, explorer,
// speedrun) only need the module/lesson TREE — ids, titles, goals, minutes.
// Importing the full registry (`@/lib/academy`) pulled every theory block,
// quiz, starter and SOLUTION into the client bundle, shipped to every visitor
// on every page. This script derives an honest, never-drifting metadata tree
// from the actual content and writes it to src/lib/academy/meta.ts.
//
// Run after any course content change:
//   bun scripts/academy-meta.ts

import { writeFileSync } from "node:fs";
import { COURSES } from "../src/lib/academy/index";

type Rec = Record<string, unknown>;

const stripSteps = (lesson: Rec): Rec => {
  const { steps: _steps, ...rest } = lesson;
  return rest;
};

const meta = COURSES.map((course) => ({
  ...course,
  modules: course.modules.map((m) => ({
    ...m,
    lessons: m.lessons.map((l) => stripSteps(l as unknown as Rec)),
  })),
}));

const totalLessons = COURSES.reduce((acc, c) => acc + c.modules.reduce((a, m) => a + m.lessons.length, 0), 0);

const out = `// TEKA NEXUS — AUTO-GENERATED academy metadata tree (no lesson steps).
// Generated by scripts/academy-meta.ts — refresh with: bun scripts/academy-meta.ts
//
// WHY: client components only need the module/lesson TREE (ids, titles,
// minutes). Full step content stays server-side in ./course-*.ts and the
// lesson player renders it from the academy chunk only. Numbers here are
// derived from the real registries, so UI counts can never drift.
import type { Course, Lesson, Module } from "./types";

export type MetaLesson = Omit<Lesson, "steps">;
export type MetaModule = Omit<Module, "lessons"> & { lessons: MetaLesson[] };
export type MetaCourse = Omit<Course, "modules"> & { modules: MetaModule[] };

export const COURSES_META: MetaCourse[] = ${JSON.stringify(meta, null, 2)} as MetaCourse[];

export function metaCourse(id: string): MetaCourse | undefined {
  return COURSES_META.find((c) => c.id === id);
}

export function metaLessons(course: MetaCourse): MetaLesson[] {
  return course.modules.flatMap((m) => m.lessons);
}

export function metaMinutes(course: MetaCourse): number {
  return metaLessons(course).reduce((acc, l) => acc + l.minutes, 0);
}
`;

const target = new URL("../src/lib/academy/meta.ts", import.meta.url);
writeFileSync(target, out);
console.log(`meta.ts written — ${COURSES.length} courses, ${COURSES.reduce((a, c) => a + c.modules.length, 0)} modules, ${totalLessons} lessons`);
